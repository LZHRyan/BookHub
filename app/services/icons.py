DEFAULT_ICON = "book-open"

_SVG = (
    '<svg class="icon@CLASS@" viewBox="0 0 24 24" width="@SIZE@" height="@SIZE@" fill="none" '
    'stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" '
    'aria-hidden="true">@BODY@</svg>'
)


def all_icons() -> list[str]:
    return [name for _, items in ICON_GROUPS for name, _ in items]


def total_icons() -> int:
    return len(all_icons())


def is_known_icon(value: str) -> bool:
    return (value or "").strip() in ICON_PATHS


def resolve_icon(value: str) -> str | None:
    """把存储值解析成图标名：本身是名字、或是已知 emoji 都算命中。"""
    # emoji 可能带 U+FE0F/U+FE0E 变体选择符（例如 🛠️），先去掉再查
    cleaned = (value or "").strip().replace("\ufe0f", "").replace("\ufe0e", "")
    if cleaned in ICON_PATHS:
        return cleaned
    alias = EMOJI_ALIASES.get(cleaned)
    if alias in ICON_PATHS:
        return alias
    return None


def icon(value: str, size: int = 20, extra_class: str = "") -> Markup:
    """渲染图标：认识就出 SVG，不认识就把原值当文本输出（老数据兜底）。"""
    name = resolve_icon(value)
    if name is None:
        raw = (value or "").strip()
        if raw:
            # 无法识别的自由文本原样输出（兼容历史上手填的内容）
            return Markup(str(escape(raw)))
        name = DEFAULT_ICON
    suffix = (" " + extra_class) if extra_class else ""
    body = ICON_PATHS[name]
    return Markup(
        _SVG.replace("@CLASS@", suffix).replace("@SIZE@", str(size)).replace("@BODY@", body)
    )
