def total_emojis() -> int:
    return sum(len(items) for _, items in EMOJI_GROUPS)


def all_emojis() -> list[str]:
    return [emoji for _, items in EMOJI_GROUPS for emoji, _ in items]


def is_known_emoji(value: str) -> bool:
    return (value or "").strip() in all_emojis()
